import React from 'react';
import { X, FileDown, CheckCircle2, Clock, Users, Award, AlertTriangle } from 'lucide-react';

interface SessionAttendee {
  id: string;
  studentName: string;
  studentId: string;
  checkInTime: string;
  status: 'present' | 'late';
}

interface SessionSummaryData {
  courseCode: string;
  courseName: string;
  lecturer: string;
  date: string;
  totalEnrolled: number;
  presentCount: number;
  lateCount: number;
  absentCount: number;
  attendanceRate: number;
  attendees: SessionAttendee[];
}

interface SessionSummaryModalProps {
  summary: SessionSummaryData;
  onClose: () => void;
}

export const SessionSummaryModal: React.FC<SessionSummaryModalProps> = ({
  summary,
  onClose,
}) => {
  const handleExportTxt = () => {
    const lines = [
      '==================================================',
      'SMART ATTENDANCE OFFICIAL CLASSROOM SESSION REPORT',
      '==================================================',
      `Course: ${summary.courseCode} - ${summary.courseName}`,
      `Lecturer: ${summary.lecturer}`,
      `Date: ${summary.date}`,
      `Total Enrolled: ${summary.totalEnrolled}`,
      `Present: ${summary.presentCount}`,
      `Late: ${summary.lateCount}`,
      `Absent: ${summary.absentCount}`,
      `Attendance Rate: ${summary.attendanceRate}%`,
      '--------------------------------------------------',
      'STUDENT ATTENDEES ROSTER:',
      '--------------------------------------------------',
      ...summary.attendees.map(
        (a, i) =>
          `${i + 1}. [${a.status.toUpperCase()}] ${a.studentName} (${a.studentId}) - Checked in at ${a.checkInTime}`
      ),
      '==================================================',
      'Generated by Smart Attendance System',
      `Timestamp: ${new Date().toLocaleString()}`,
    ];

    const content = lines.join('\n');
    const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `Attendance_${summary.courseCode.replace(/\s+/g, '_')}_${summary.date.replace(/[^a-zA-Z0-9]/g, '_')}.txt`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 bg-black/60 backdrop-blur-xs flex items-end sm:items-center justify-center p-0 sm:p-4 animate-in fade-in duration-200">
      <div className="w-full sm:max-w-md max-h-[90vh] rounded-t-3xl sm:rounded-2xl bg-[#FAF8F3] border border-[#E8DCC8] flex flex-col shadow-2xl overflow-hidden">
        {/* Header */}
        <div className="p-4 border-b border-[#E8DCC8] flex items-center justify-between bg-[#E8DCC8]/40">
          <div>
            <span className="text-[11px] font-bold text-[#1F2A44] uppercase tracking-wider font-heading">
              Session Closed
            </span>
            <h2 className="text-base font-extrabold text-[#1F2A44] font-heading">
              Attendance Summary
            </h2>
          </div>
          <button
            onClick={onClose}
            className="w-8 h-8 rounded-full bg-white border border-[#E8DCC8] flex items-center justify-center text-[#1F2A44] hover:bg-[#E8DCC8] cursor-pointer"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        <div className="overflow-y-auto no-scrollbar p-5 space-y-4">
          {/* Main Rate Hero in Navy */}
          <div className="p-4 rounded-2xl bg-[#1F2A44] text-[#FAF8F3] text-center space-y-1 shadow-xs">
            <span className="text-xs font-semibold text-[#C6A75E]">
              {summary.courseCode} · {summary.courseName}
            </span>
            <div className="text-4xl font-extrabold font-heading tabular-nums">
              {summary.attendanceRate}%
            </div>
            <p className="text-xs text-[#FAF8F3]/80">
              {summary.presentCount + summary.lateCount} of {summary.totalEnrolled} students verified
            </p>
          </div>

          {/* Metrics 4-Grid */}
          <div className="grid grid-cols-4 gap-2 text-center">
            <div className="p-2.5 rounded-xl bg-white border border-[#E8DCC8]">
              <span className="text-base font-extrabold text-[#1F2A44] font-heading tabular-nums">
                {summary.totalEnrolled}
              </span>
              <p className="text-[9px] font-bold text-[#706B62] uppercase">Enrolled</p>
            </div>
            <div className="p-2.5 rounded-xl bg-[#4F8A67]/15 border border-[#4F8A67]/25">
              <span className="text-base font-extrabold text-[#4F8A67] font-heading tabular-nums">
                {summary.presentCount}
              </span>
              <p className="text-[9px] font-bold text-[#4F8A67] uppercase">Present</p>
            </div>
            <div className="p-2.5 rounded-xl bg-[#C28B3C]/15 border border-[#C28B3C]/25">
              <span className="text-base font-extrabold text-[#C28B3C] font-heading tabular-nums">
                {summary.lateCount}
              </span>
              <p className="text-[9px] font-bold text-[#C28B3C] uppercase">Late</p>
            </div>
            <div className="p-2.5 rounded-xl bg-[#B95757]/15 border border-[#B95757]/25">
              <span className="text-base font-extrabold text-[#B95757] font-heading tabular-nums">
                {summary.absentCount}
              </span>
              <p className="text-[9px] font-bold text-[#B95757] uppercase">Absent</p>
            </div>
          </div>

          {/* Attendee Roster Snippet */}
          <div className="space-y-2">
            <h4 className="text-xs font-bold text-[#1F2A44] font-heading uppercase tracking-wider">
              Check-in Log ({summary.attendees.length})
            </h4>

            <div className="max-h-48 overflow-y-auto no-scrollbar space-y-1.5 border border-[#E8DCC8] rounded-xl p-2 bg-white">
              {summary.attendees.map((att, i) => (
                <div
                  key={att.id}
                  className="flex items-center justify-between text-xs p-1.5 rounded-lg bg-[#FAF8F3] border border-[#E8DCC8]"
                >
                  <div className="flex items-center gap-2">
                    <span className="text-[10px] font-bold text-[#706B62] w-4">
                      {i + 1}.
                    </span>
                    <div>
                      <p className="font-bold text-[#1F2A44] leading-tight">
                        {att.studentName}
                      </p>
                      <p className="text-[10px] text-[#706B62]">{att.studentId}</p>
                    </div>
                  </div>

                  <div className="text-right">
                    <span
                      className={`text-[10px] font-bold px-2 py-0.5 rounded-full capitalize ${
                        att.status === 'present'
                          ? 'bg-[#4F8A67]/15 text-[#4F8A67]'
                          : 'bg-[#C28B3C]/15 text-[#C28B3C]'
                      }`}
                    >
                      {att.status} · {att.checkInTime}
                    </span>
                  </div>
                </div>
              ))}

              {summary.attendees.length === 0 && (
                <p className="text-xs text-[#706B62] text-center py-4 italic">
                  No students checked in during this session.
                </p>
              )}
            </div>
          </div>

          {/* Export Action */}
          <button
            onClick={handleExportTxt}
            className="w-full h-11 rounded-xl bg-[#1F2A44] text-[#FAF8F3] font-heading font-bold text-xs flex items-center justify-center gap-2 shadow-xs hover:bg-[#2b3a5c] active:scale-[0.98] transition-all cursor-pointer"
          >
            <FileDown className="w-4 h-4 text-[#C6A75E]" />
            <span>Export Attendance as .txt File</span>
          </button>
        </div>

        <div className="p-4 border-t border-[#E8DCC8] bg-white">
          <button
            onClick={onClose}
            className="w-full py-2.5 rounded-xl bg-[#FAF8F3] hover:bg-[#E8DCC8] text-[#1F2A44] border border-[#E8DCC8] text-xs font-bold font-heading cursor-pointer transition-colors"
          >
            Return to Dashboard
          </button>
        </div>
      </div>
    </div>
  );
};

